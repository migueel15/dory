// Textf is Text used as a format with args.
func Textf(code string, args ...any) string { return fmt.Sprintf(Text(code), args...) }

// Text is the Spanish text of a code, or the code itself when it has none.
func Text(code string) string {
	if s, ok := es[code]; ok {
		return s
	}
	return code
}
